"""Генерация прозаических разделов РПД (актуальность, цели, паспорт) через LLM.

Разделы-проза не переносятся из УП — их генерирует LLM по теме и содержанию УП, с учётом правил из
комментариев методиста (актуальность — развёрнуто, цели — поверхностно/общей фразой). Без клиента или
при ошибке возвращаем пусто → рендер подставит плейсхолдер.
"""

from __future__ import annotations

from typing import Any

from .up_models import UpPlan

_SYSTEM = (
    "Ты методист ДПО. Пишешь официальные формулировки для рабочей программы дисциплины на русском. "
    "Опирайся ТОЛЬКО на данные программы, которые тебе дают (тема, модули, компетенции). Без воды, по делу, "
    "без выдуманных фактов и без английских слов, кроме терминов и имён собственных."
)

# (matcher-substring, инструкция). Порядок важен: более узкие проверки — выше.
_PROMPTS: list[tuple[str, str]] = [
    ("актуальн", "Напиши «Актуальность программы» (2–3 абзаца): почему эта тема востребована, кому и зачем нужна именно эта программа. Свяжи с её модулями."),
    ("паспорт оцен", "Опиши общий состав оценочных материалов программы: виды заданий (проекты по модулям) и форму проверки (p2p, защита). Без конкретных заданий."),
    ("паспорт", "Напиши аннотацию-паспорт программы (3–5 предложений): о чём программа, для кого, какой результат — по её модулям."),
    ("характеристика", "Кратко опиши область и виды профессиональной деятельности, к которым готовит программа (1 абзац), исходя из её модулей."),
    ("цель", "Сформулируй цель программы (1 фраза) и 3–4 задачи (списком) — по её модулям. Кратко."),
    ("цели", "Сформулируй цель программы (1 фраза) и 3–4 задачи (списком) — по её модулям. Кратко."),
    ("задач", "Сформулируй цель программы (1 фраза) и 3–4 задачи (списком) — по её модулям."),
    ("текущий контроль", "Опиши текущий контроль в общем виде: выполнение практических проектов по модулям, p2p-проверки. 1 абзац."),
    ("итоговая аттест", "Опиши итоговую аттестацию в общем виде (защита итогового проекта / итоговый тест), официально. 1 абзац."),
    ("учебно-методич", "Опиши учебно-методическое и информационное обеспечение в общем виде (материалы, платформа, ПО из модулей). 1 абзац."),
    ("материально", "Опиши материально-технические условия в общем виде (оборудование, ПО, доступ к платформе). 1 абзац."),
    ("кадров", "Опиши кадровое обеспечение в общем виде (требования к преподавателям), официально. 1 абзац."),
    ("пример оформления", "Опиши, что должно содержаться в примере оформления учебного модуля (структура задания, критерии оценки). Кратко."),
    ("пример оценки", "Опиши, что показывает пример оценки (задание, критерии, результат). Кратко."),
]


def generate_prose(section_title: str, up: UpPlan, client: Any) -> list[str]:
    """Возвращает абзацы сгенерированного текста для раздела-прозы; пусто → рендер даст плейсхолдер."""
    instruction = _instruction_for(section_title)
    if instruction is None or client is None:
        return []
    user = f"{instruction}\n\n{_up_context(up)}"
    try:
        text = str(client.complete(_SYSTEM, user))
    except Exception:  # noqa: BLE001 - генерация best-effort; при сбое падаем в плейсхолдер
        return []
    return [_strip_markdown(line) for line in text.splitlines() if line.strip()]


def _strip_markdown(line: str) -> str:
    """Убирает markdown-разметку (**жирный**, ##, списочные маркеры) — в DOCX она показалась бы текстом."""
    cleaned = line.strip().lstrip("#").strip()
    cleaned = cleaned.replace("**", "").replace("__", "")
    if cleaned[:2] in {"- ", "* "}:
        cleaned = "• " + cleaned[2:]
    return cleaned.strip()


def _instruction_for(title: str) -> str | None:
    low = title.lower()
    for needle, instruction in _PROMPTS:
        if needle in low:
            return instruction
    return None


def _up_context(up: UpPlan) -> str:
    modules = "\n".join(f"- {module.title}" for module in up.modules[:15])
    outcomes = "; ".join(up.all_outcomes()[:12])
    competencies = "; ".join(comp.code for comp in up.competencies()[:12])
    return (
        f"Название программы: {up.title or 'не указано'}\n"
        f"Объём: {up.total_hours or '—'} академических часов\n"
        f"Модулей: {len(up.modules)}\n"
        f"Модули:\n{modules}\n"
        f"Компетенции (навыки): {competencies or '—'}\n"
        f"Ключевые результаты: {outcomes or '—'}"
    )
