"""Общий контракт перевода: что вынимаем из файла и как возвращаем обратно.

Один контракт на все форматы. Существенное свойство — ``apply`` получает исходные байты, а не
собирает файл заново: вёрстка сохраняется по построению, а не стараниями модели. Модель видит
только список строк и возвращает список строк, испортить файл она не может.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol, runtime_checkable


@dataclass(frozen=True)
class TextUnit:
    """Один переводимый кусок текста внутри файла.

    ``unit_id`` — устойчивый ключ, по которому перевод вернётся на своё место; он же едет к модели,
    поэтому должен быть коротким. ``hint`` подсказывает модели, что это за текст («заголовок
    колонки», «комментарий»), и на размещение не влияет.
    """

    unit_id: str
    text: str
    hint: str = ""


